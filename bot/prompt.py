def system_blocks(prompt: str, admin: bool = False) -> list[dict]:
    """Системный промпт неизменен — кэшируется между запросами.

    Пометка администратора — отдельным блоком после точки кэша, кэш основного промпта общий.
    """
    blocks = [{"type": "text", "text": prompt, "cache_control": {"type": "ephemeral"}}]
    if admin:
        blocks.append({"type": "text", "text": ADMIN_NOTE})
    return blocks


def build_messages(history: list[dict], question: str, context_text: str, info: str) -> list[dict]:
    """История + текущий вопрос с найденным контекстом.

    Контекст прикладывается только к текущему вопросу, поэтому история не раздувается
    и кэшируется как префикс.
    """
    messages = [dict(m) for m in history]
    if messages:
        # Точка кэша на конце истории: следующий запрос прочитает её из кэша
        last = messages[-1]
        last["content"] = [{"type": "text", "text": last["content"],
                            "cache_control": {"type": "ephemeral"}}]
    messages.append({
        "role": "user",
        "content": f"Контекст:\n{context_text}\n\n{info}\n\n{question}",
    })
    return messages
